import { createReadStream, createWriteStream } from 'node:fs';
import { mkdir, rename, stat, unlink } from 'node:fs/promises';
import path from 'node:path';
import type { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import type { Storage, StoredObject } from './storage';

const SAFE_KEY = /^[A-Za-z0-9_-]+\.[a-z0-9]+$/;

export class LocalDiskStorage implements Storage {
  constructor(private readonly root: string) {}

  async put(key: string, data: Readable): Promise<number> {
    const target = this.resolve(key);
    await mkdir(path.dirname(target), { recursive: true });
    // Write to a temp file first so readers never see a half-written upload.
    const temp = `${target}.part`;
    try {
      await pipeline(data, createWriteStream(temp));
      await rename(temp, target);
    } catch (error) {
      await unlink(temp).catch(() => {});
      throw error;
    }
    return (await stat(target)).size;
  }

  async get(key: string): Promise<StoredObject | null> {
    const target = this.resolve(key);
    try {
      const { size } = await stat(target);
      return { size, stream: createReadStream(target) };
    } catch {
      return null;
    }
  }

  async ping(): Promise<void> {
    await mkdir(this.root, { recursive: true });
  }

  /** Keys are generated by the service, but never trust them to build paths. */
  private resolve(key: string): string {
    if (!SAFE_KEY.test(key)) throw new Error(`Unsafe storage key: ${key}`);
    return path.join(this.root, key.slice(0, 2), key);
  }
}
